/** Экран, который сейчас показывает модалка входа. */
export enum AuthScreen {
  /** Ввод номера телефона. С него модалка всегда открывается. */
  phone = 'phone',
  /** Ввод кода из SMS. */
  code = 'code',
  /** Анимация «Авторизуем вас», пока идёт вход и добирается минимальное время. */
  success = 'success',
  /** Экран «Что-то пошло не так» с кнопкой закрытия. */
  error = 'error',
}
